#!/usr/bin/env python
r"""
build_stygia_tint.py -- while Blessing of Stygia is active, world-map water is drawn slightly darker
and purpler (owner 2026-10-25: option H of three, "only slightly darker and slightly purpler than
default water, surface and cave both").  Images/Waterhex.ILB + _Waterhex.ILB, AoWEPACK.dpl.

THE ART  every pixel of the shipped image with its hue turned HUE_TURN degrees toward purple and its
  value scaled by VALUE (saturation kept), appended to Waterhex.ILB and, from its own half-size
  originals or halved, to _Waterhex.ILB (both twins: a new id must exist in both, 07-ui.md §7.1),
  before each directory's closing -1:
    224-239  the base water tiles 140-155 (TAoWWaterHexagon.Show's 0x8C + n)
    240-303  build_skychasm_edges.py's Sky/Chasm fades 160-223, regenerated by its own water_fades()
             from the recoloured water texture (the fades mix water with the void)
    304-307  the four underground-Water tiles (Release.hss's embedded terrain-0x0A resources, file
             order), each standing in for its resource's one-image library entry 0
  The sand, snow and wasteland shore pieces hold no water (the base tile shows through their
  dither), so they need no twin.  The animated glints (WaterAnm.ILB, dark greys drawn blended), the
  ice edges and the cave-water/void dissolves in HEXTRANS.ILB stay as they are.
THE SWAP  TAoWHSMap's VMT (0x5570E874; the battle map, TAoWCombatMap, has its own) slots +0xE0
  DrawStaticScene (0x5570E954) and +0xE4 DrawDynamicScene (0x5570E958) -> cave_ds / cave_dd (.reloc
  kept), which call the originals.  Around each call, while Stygia is active, the image-library
  entries ({image, alias} at [lib+0x48] + id*8, count [lib+0x44]) of each original id and its twin
  are exchanged, and exchanged back after; an image loads from its own library wherever its entry
  sits, so nothing else changes, and exchanging is its own inverse.  The libraries are found each
  time: the terrain control [AoWHSSet+0x18], its per-terrain lists [[ctrl+0x10]+4][terrain]; water
  (0): the resource with ClassID 0x2073E, Waterhex = its image sequence 0's library; underground
  Water (0x0A): the resources with ClassID 0x20153, each one's tile library at [res+0x20].  An id
  past a library's count or a nil image is skipped.
  Active = build_blessing_stygia.py's pinned STY_ANY (0x558BD800, called only while its first
  byte is the E9 of its entry): an active Blessing of Stygia record exists.  The base tiles live in
  the cached static scene: cave_ds latches the state it draws with (BSS 0x558FAC04); cave_dd draws
  the dynamic pass with the latched state, and when the live state differs it sets the map's
  "static scene invalid" flag [map+0x30] -- after the frame's last static draw, so the next frame
  rebuilds the cache in the new state.  BSS 0x558FAC05 records that entries are exchanged, so an
  exception inside a draw is repaired at the next call.  Loads, Disjunction and unpaid upkeep need
  nothing: the state is read from the global magic list every frame.

RNG: none.  Drawing only; no game state changes, so every peer stays in step.
Slot 0x558BE000-0x558BE3FF, exclusive.  PIC.  Surgical --undo (code first, then the images).
Couplings
  * build_skychasm_edges.py owns the ids just below ours: its ilb_strip refuses while ours follow
    its tail.  Undo this script before undoing or re-tuning it, and re-apply this one after.
  * build_blessing_stygia.py provides STY_ANY; without it the water is never tinted.
Unproven, static checks cannot reach it: how it looks in game; the half-size file's role.

    python build_scripts/build_stygia_tint.py            dry run + state
    python build_scripts/build_stygia_tint.py --apply
    python build_scripts/build_stygia_tint.py --undo
    python build_scripts/build_stygia_tint.py --dis
"""
import colorsys, os, struct, sys
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "re_tools"))
import aowepack_patch as P
from aowepack_patch import asm, run, kill_aow
from piccave import pic
import hexfield as hf

HUE_TURN, VALUE = 20, 0.88
IMG = os.path.join(P.GAME, "Images")
HSS = os.path.join(P.GAME, "Release", "Release.hss")
FILES = [(os.path.join(IMG, "Waterhex.ILB"), False), (os.path.join(IMG, "_Waterhex.ILB"), True)]
BASE_IDS = list(range(140, 156))
FADE_IDS = list(range(160, 224))
TWIN_BASE, TWIN_FADE, TWIN_CAVE = 224, 240, 304
N_CAVE = 4
OUR_IDS = set(range(TWIN_BASE, TWIN_CAVE + N_CAVE))
NAME = "zstygia_water.BMP"

SLOT = (0x558BE000, 0x558BE400)
VMT_MAP = 0x5570E874
SLOT_DS, SLOT_DD = VMT_MAP + 0xE0, VMT_MAP + 0xE4
ORIG_DS, ORIG_DD = 0x5570263C, 0x55778A60
STY_ANY = 0x558BD800
LATCHED, SWAPPED = 0x558FAC04, 0x558FAC05
AOWHSSET = 0x558FA044
GETSEQ = 0x557028E4
CID_WATER, CID_CAVE = 0x2073E, 0x20153
T_WATER, T_CAVE = 0x00, 0x0A
A = {}


# ----------------------------------------------------------------------------- art
def recolour(im):
    out = im.copy()
    px = out.load()
    for y in range(im.size[1]):
        for x in range(im.size[0]):
            r, g, b, a = px[x, y]
            if not a:
                continue
            h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
            r2, g2, b2 = colorsys.hsv_to_rgb(((h * 360 + HUE_TURN) % 360) / 360, s, v * VALUE)
            px[x, y] = (int(round(r2 * 255)), int(round(g2 * 255)), int(round(b2 * 255)), 255)
    return out


_ART = {}


def full_art():
    """{twin id: full-size image} for the twins not made from each file's own originals."""
    if _ART:
        return _ART
    import importlib.util
    spec = importlib.util.spec_from_file_location("_sky", os.path.join(HERE, "build_skychasm_edges.py"))
    SK = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(SK)
    wl = hf.Lib(FILES[0][0])
    tiles = hf.hss_tiles(HSS)
    water = recolour(wl.get(0x8C))
    for vt in SK.VOIDS:
        for k, im in SK.water_fades(SK.Tex(water), SK.Tex(tiles[vt][0])).items():
            _ART[TWIN_FADE + SK.WBASE[vt] + k - FADE_IDS[0]] = im
    cave = tiles[T_CAVE]
    assert len(cave) == N_CAVE, "Release.hss holds %d underground-Water tiles, not %d" % (len(cave), N_CAVE)
    for k, im in enumerate(cave):
        _ART[TWIN_CAVE + k] = recolour(im)
    return _ART


def ilb_plan(undo):
    import importlib.util
    spec = importlib.util.spec_from_file_location("_sky2", os.path.join(HERE, "build_skychasm_edges.py"))
    SK = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(SK)
    out = []
    for path, half in FILES:
        d = open(path, "rb").read()
        base = hf.ilb_strip(d, OUR_IDS)
        R = hf.read_records(base)
        recs = {r['id']: r for r in R['recs']}
        clash = [i for i in recs if i in OUR_IDS]
        if clash:
            sys.exit("ABORT: %s already uses ids %s" % (os.path.basename(path), clash[:6]))
        for i in BASE_IDS + FADE_IDS + [0x8C]:
            if i not in recs:
                sys.exit("ABORT: %s lacks image %d" % (os.path.basename(path), i))
        if undo:
            out.append((path, d, base))
            continue
        lib = hf.Lib(data=base)
        items = []
        for k, i in enumerate(BASE_IDS):
            tpl = recs[i]
            assert tpl['xsh'] == tpl['ysh'] == 0, "image %d is shifted" % i
            items.append(hf.image_record(tpl, TWIN_BASE + k, NAME, recolour(lib.get(i)), tpl['tr']))
        art = full_art()
        for iid in sorted(art):
            tpl = recs[FADE_IDS[0]] if iid < TWIN_CAVE else recs[0x8C]
            im = SK.halve(art[iid]) if half else art[iid]
            items.append(hf.image_record(tpl, iid, NAME, im, tpl['tr']))
        new = hf.ilb_append(base, items)
        R0, R1 = hf.read_records(base), hf.read_records(new)
        f = lambda r: {k: v for k, v in r.items() if k not in ('start', 'raw')}
        m1 = {r['id']: r for r in R1['recs']}
        for r in R0['recs']:
            assert f(m1[r['id']]) == f(r), "shipped record %d changed" % r['id']
            a = base[R0['imgdir'] + r['offset']:][:r['size']]
            b = new[R1['imgdir'] + r['offset']:][:r['size']]
            assert a == b, "shipped pixels %d changed" % r['id']
        assert set(m1) - set(recs) == OUR_IDS
        out.append((path, d, new))
    return out


# ----------------------------------------------------------------------------- code
def c_lib_entry(va):
    """entry(eax = library, edx = id) -> eax = &entry, or 0 when out of range or nil."""
    return asm(f"""
        test eax, eax
        je   e_no
        cmp  edx, dword ptr [eax + 0x44]
        jae  e_no
        mov  eax, dword ptr [eax + 0x48]
        test eax, eax
        je   e_no
        lea  eax, [eax + edx*8]
        cmp  dword ptr [eax], 0
        je   e_no
        ret
    e_no:
        xor  eax, eax
        ret
    """, va)


def c_xchg(va):
    """xchg(eax = lib A, edx = id A, ecx = lib B, [esp+4] = id B): exchange the two entries; ret 4."""
    return asm(f"""
        push ebx
        push esi
        push edi
        mov  esi, ecx
        call {A['entry']:#x}
        test eax, eax
        je   x_out
        mov  edi, eax
        mov  eax, esi
        mov  edx, dword ptr [esp + 0x10]
        call {A['entry']:#x}
        test eax, eax
        je   x_out
        mov  ecx, dword ptr [eax]
        mov  edx, dword ptr [edi]
        mov  dword ptr [eax], edx
        mov  dword ptr [edi], ecx
        mov  ecx, dword ptr [eax + 4]
        mov  edx, dword ptr [edi + 4]
        mov  dword ptr [eax + 4], edx
        mov  dword ptr [edi + 4], ecx
    x_out:
        pop  edi
        pop  esi
        pop  ebx
        ret  4
    """, va)


def c_find(va):
    """find(eax = TList, edx = ClassID, ecx = n-th match) -> eax resource or 0."""
    return asm(f"""
        push ebx
        push esi
        push edi
        push ebp
        test eax, eax
        je   f_no
        mov  esi, eax
        mov  edi, edx
        mov  ebp, ecx
        xor  ebx, ebx
    f_loop:
        cmp  ebx, dword ptr [esi + 8]
        jge  f_no
        mov  eax, dword ptr [esi + 4]
        mov  eax, dword ptr [eax + ebx*4]
        inc  ebx
        test eax, eax
        je   f_loop
        push eax
        mov  edx, dword ptr [eax]
        call dword ptr [edx + 0x24]
        cmp  eax, edi
        pop  eax
        jne  f_loop
        dec  ebp
        jns  f_loop
        jmp  f_out
    f_no:
        xor  eax, eax
    f_out:
        pop  ebp
        pop  edi
        pop  esi
        pop  ebx
        ret
    """, va)


def c_swap(va):
    """Exchange every original/twin pair once.  Locals: [esp] the per-terrain list array,
    [esp+4] Waterhex, [esp+8] the loop."""
    src = f"""
        push ebx
        push esi
        push edi
        sub  esp, 0xc
        {{ANC}}
        mov  eax, dword ptr [ebx + {{SET}}]
        test eax, eax
        je   w_out
        mov  eax, dword ptr [eax + 0x18]
        test eax, eax
        je   w_out
        mov  eax, dword ptr [eax + 0x10]
        test eax, eax
        je   w_out
        cmp  dword ptr [eax + 8], {T_CAVE + 1}
        jl   w_out
        mov  eax, dword ptr [eax + 4]
        mov  dword ptr [esp], eax
        mov  eax, dword ptr [eax + {T_WATER * 4}]
        mov  edx, {CID_WATER:#x}
        xor  ecx, ecx
        call {A['find']:#x}
        test eax, eax
        je   w_out
        mov  eax, dword ptr [eax + 0x24]
        test eax, eax
        je   w_out
        xor  edx, edx
        call {GETSEQ:#x}
        test eax, eax
        je   w_out
        mov  esi, dword ptr [eax + 0x10]
        test esi, esi
        je   w_out
        mov  dword ptr [esp + 4], esi
        xor  edi, edi
    w_base:
        lea  eax, [edi + {TWIN_BASE}]
        push eax
        lea  edx, [edi + {BASE_IDS[0]}]
        mov  eax, esi
        mov  ecx, esi
        call {A['xchg']:#x}
        inc  edi
        cmp  edi, {len(BASE_IDS)}
        jl   w_base
        xor  edi, edi
    w_fade:
        lea  eax, [edi + {TWIN_FADE}]
        push eax
        lea  edx, [edi + {FADE_IDS[0]}]
        mov  eax, esi
        mov  ecx, esi
        call {A['xchg']:#x}
        inc  edi
        cmp  edi, {len(FADE_IDS)}
        jl   w_fade
        xor  edi, edi
    w_cave:
        mov  eax, dword ptr [esp]
        mov  eax, dword ptr [eax + {T_CAVE * 4}]
        mov  edx, {CID_CAVE:#x}
        mov  ecx, edi
        call {A['find']:#x}
        test eax, eax
        je   w_out
        mov  eax, dword ptr [eax + 0x20]
        lea  edx, [edi + {TWIN_CAVE}]
        push edx
        xor  edx, edx
        mov  ecx, dword ptr [esp + 8]
        call {A['xchg']:#x}
        inc  edi
        cmp  edi, {N_CAVE}
        jl   w_cave
    w_out:
        add  esp, 0xc
        pop  edi
        pop  esi
        pop  ebx
        ret
    """
    return pic(src, va, "ebx", {"SET": AOWHSSET})


def c_active(va):
    """-> eax 1 when build_blessing_stygia.py is applied and a record is active."""
    src = f"""
        {{ANC}}
        cmp  byte ptr [ecx + {{ANY}}], 0xe9
        jne  a_no
        call {STY_ANY:#x}
        movzx eax, al
        ret
    a_no:
        xor  eax, eax
        ret
    """
    return pic(src, va, "ecx", {"ANY": STY_ANY})


def c_ds(va):
    """TAoWHSMap +0xE0 DrawStaticScene(eax = map, edx = surface)."""
    src = f"""
        push ebx
        push esi
        push edi
        mov  esi, eax
        mov  edi, edx
        {{ANC}}
        cmp  byte ptr [ebx + {{SWAPPED}}], 0
        je   d_fresh
        call {A['swap']:#x}
        mov  byte ptr [ebx + {{SWAPPED}}], 0
    d_fresh:
        call {A['active']:#x}
        mov  byte ptr [ebx + {{LATCHED}}], al
        test al, al
        je   d_call
        call {A['swap']:#x}
        mov  byte ptr [ebx + {{SWAPPED}}], 1
    d_call:
        mov  eax, esi
        mov  edx, edi
        call {ORIG_DS:#x}
        cmp  byte ptr [ebx + {{SWAPPED}}], 0
        je   d_out
        call {A['swap']:#x}
        mov  byte ptr [ebx + {{SWAPPED}}], 0
    d_out:
        pop  edi
        pop  esi
        pop  ebx
        ret
    """
    return pic(src, va, "ebx", {"SWAPPED": SWAPPED, "LATCHED": LATCHED})


def c_dd(va):
    """TAoWHSMap +0xE4 DrawDynamicScene(eax = map, edx = surface)."""
    src = f"""
        push ebx
        push esi
        push edi
        mov  esi, eax
        mov  edi, edx
        {{ANC}}
        cmp  byte ptr [ebx + {{SWAPPED}}], 0
        je   y_fresh
        call {A['swap']:#x}
        mov  byte ptr [ebx + {{SWAPPED}}], 0
    y_fresh:
        cmp  byte ptr [ebx + {{LATCHED}}], 0
        je   y_call
        call {A['swap']:#x}
        mov  byte ptr [ebx + {{SWAPPED}}], 1
    y_call:
        mov  eax, esi
        mov  edx, edi
        call {ORIG_DD:#x}
        cmp  byte ptr [ebx + {{SWAPPED}}], 0
        je   y_state
        call {A['swap']:#x}
        mov  byte ptr [ebx + {{SWAPPED}}], 0
    y_state:
        call {A['active']:#x}
        cmp  al, byte ptr [ebx + {{LATCHED}}]
        je   y_out
        mov  byte ptr [esi + 0x30], 1
    y_out:
        pop  edi
        pop  esi
        pop  ebx
        ret
    """
    return pic(src, va, "ebx", {"SWAPPED": SWAPPED, "LATCHED": LATCHED})


BUILDERS = [("entry", c_lib_entry), ("xchg", c_xchg), ("find", c_find), ("swap", c_swap),
            ("active", c_active), ("ds", c_ds), ("dd", c_dd)]


def layout():
    for name, _b in BUILDERS:
        A.setdefault(name, SLOT[0] + 0x300)
    for _ in range(3):
        va, blobs = SLOT[0], []
        for name, b in BUILDERS:
            A[name] = va
            blob = b(va)
            blobs.append(("cave_" + name, va, blob))
            va = (va + len(blob) + 15) & ~15
    assert va <= SLOT[1], "slot overflow"
    return blobs


def checks(d):
    u = lambda v: struct.unpack_from("<I", d, P.va2off(d, v))[0]
    cn = P.va2off(d, u(VMT_MAP - 0x20))
    if u(VMT_MAP - 0x40) != VMT_MAP or d[cn + 1:cn + 1 + d[cn]] != b"TAoWHSMap":
        sys.exit("ABORT: TAoWHSMap's VMT moved")
    for a in range(LATCHED, LATCHED + 2):
        if struct.pack("<I", a) in d:
            sys.exit("ABORT: something already addresses BSS %08X" % a)


def main():
    blobs = layout()
    d = open(P.TARGET, "rb").read()
    pk = lambda v: struct.pack("<I", v)
    hooks = [(SLOT_DS, pk(ORIG_DS), pk(A["ds"])), (SLOT_DD, pk(ORIG_DD), pk(A["dd"]))]
    apply_, undo = "--apply" in sys.argv, "--undo" in sys.argv
    code_state = "installed" if all(d[P.va2off(d, va):P.va2off(d, va) + 4] == new for va, _o, new in hooks) else "not installed"
    if code_state != "installed":
        checks(d)
    plan = ilb_plan(undo)
    for path, old, new in plan:
        print("  %s: %s" % (os.path.basename(path), "current" if old == new else "%d -> %d B" % (len(old), len(new))))
    if undo:
        run("build_stygia_tint -- the Stygian water (AoWEPACK)", hooks, blobs, SLOT, [],
            reloc_ok=(SLOT_DS, SLOT_DD))
    if (apply_ or undo) and any(old != new for _p, old, new in plan):
        kill_aow()
        for path, old, new in plan:
            if old != new:
                open(path, "wb").write(new)
                print("    %s %s" % ("RESTORED" if undo else "WRITTEN", os.path.basename(path)))
    if not undo:
        run("build_stygia_tint -- the Stygian water (AoWEPACK)", hooks, blobs, SLOT, [],
            reloc_ok=(SLOT_DS, SLOT_DD))


if __name__ == "__main__":
    main()
